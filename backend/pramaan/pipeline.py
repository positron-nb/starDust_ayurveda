NEG_RE = re.compile(rf"(?<![{IAST_LETTERS}])(?:na|nā|naiva|varjayet|varjayed|tyajet|tyajed|varjya\w*|niṣiddh\w*|ahita\w*|a-hita\w*)(?![{IAST_LETTERS}])")
INTERACTION_RE = re.compile(r"\binteract\w*|\btogether with\b|\balong with\b|\bwith my (?:medicine|medication|tablets?)\b|\bcombine\w*\b|परस्पर|के साथ ले", re.I)
LOCATOR_RE = re.compile(r"\b(Ca|Ah)\.(\d{1,2})\.(\d{1,3})\.(\d{1,4}(?:[-+]\d+)*)\b")
NAMED_LOCATOR_RE = re.compile(
    r"\b(charaka|caraka|ashtanga\s*hridaya|aṣṭāṅga\s*hṛdaya|astanga\s*hrdaya|ah)\b[\s,]*"
    r"(sutra|sūtra|su|sū|nidana|nidāna|vimana|vimāna|sharira|śārīra|sarira|indriya|chikitsa|cikitsā|cikitsa|chikitsita|kalpa|siddhi|uttara)\w*"
    r"[\s,]*(\d{1,3})\s*[.:/]\s*(\d{1,4})", re.I)
STHANA_NUM = {
    "Ca": {"su": 1, "nid": 2, "vim": 3, "sha": 4, "sar": 4, "śār": 4, "ind": 5, "chi": 6, "cik": 6, "kal": 7, "sid": 8},
    "Ah": {"su": 1, "sū": 1, "sha": 2, "sar": 2, "śār": 2, "nid": 3, "chi": 4, "cik": 4, "kal": 5, "utt": 6},
}

