"""The PRAMAAN pipeline as direct, inspectable functions:

normalize -> extract/merge facts -> safety precheck (escalation) -> [AyurParam concept expansion]
-> hybrid retrieval -> answerability -> context-limiting search -> safety rules -> evidence
selection under the real token budget -> [AyurParam evidence-bounded explanation] -> ledger
validation -> render.
"""
