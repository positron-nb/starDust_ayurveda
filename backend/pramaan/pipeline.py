def now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _boundary(run_id: str, n: int, text: str, meta: dict, locations: list[str] | None = None) -> Claim:
    return Claim(
        claim_id=f"{run_id}-b{n}", text=text, claim_type="boundary_statement", evidence_ids=[],
        source_locations=locations or [], interpretation_status="deterministic_template",
        citation_integrity=CitationIntegrity(status="pass", checks={"deterministic_template": True}),
        support_assessment="source_statement", support_detail="System boundary statement (not a domain claim).",
        limitations=[], run_id=run_id, **meta,
    )


def _safety_claim(run_id: str, n: int, a: SafetyAlert, meta: dict) -> Claim:
    loc = [f"{a.source_id}: {a.statement_id} ({a.source_url})"] if a.statement_id else [f"policy rule {a.rule_id}"]
    return Claim(
        claim_id=f"{run_id}-s{n}", text=a.message, claim_type="safety_statement", evidence_ids=[],
        source_locations=loc, interpretation_status="deterministic_template",
        citation_integrity=CitationIntegrity(status="pass", checks={"rule_exists": True, "statement_exists": bool(a.statement_id) or a.basis_type == "product_policy"}),
        support_assessment="source_statement",
        support_detail=("Modern safety reference statement (paraphrase); scope: " + (a.statement_scope or "")) if a.basis_type == "modern_safety_source"
        else "Product policy restriction - not a classical contraindication.",
        limitations=["Rule review status: " + a.review_status], run_id=run_id, **meta,
    )


class Engine:
    def __init__(self, store: CorpusStore, terms: Terminology, policy: Policy, llm: LLMAdapter,
                 retriever: Retriever | None = None):
        self.store = store
        self.terms = terms
        self.policy = policy
        self.llm = llm
        self.retriever = retriever or Retriever(store, terms)

    # ---------------------------------------------------------------- helpers
    def cache_key(self, req: QueryRequest, facts: list[CaseFact]) -> str:
        payload = {
            "q": nfc(req.query), "lang": req.lang, "case": nfc(req.case_text or ""),
            "facts": [f.model_dump(include={"key", "state", "values"}) for f in facts],
            "filter": req.source_filter, "mode": req.retrieval_mode, "use_model": req.use_model,
            "model": AYURPARAM_MODEL_ID, "rev": AYURPARAM_REVISION, "prompt": PROMPT_VERSION,
            "corpus": self.store.corpus_version(), "rules": self.policy.version, "terms": self.terms.version,
            "llm_mode": self.llm.mode,
        }
        return hashlib.sha256(json.dumps(payload, sort_keys=True, ensure_ascii=False).encode()).hexdigest()

    def requested_locators(self, text: str) -> list[tuple[str, str | None]]:
        """Return [(display, passage_id_or_None)] for explicit verse references in the query."""
        out = []
        for m in LOCATOR_RE.finditer(text):
            pid = f"{m.group(1)}.{int(m.group(2))}.{int(m.group(3))}.{m.group(4)}"
            out.append((m.group(0), pid))
        for m in NAMED_LOCATOR_RE.finditer(text):
            work = "Ca" if m.group(1).lower().startswith(("cha", "car")) else "Ah"
            key = m.group(2).lower()[:3]
            sth = STHANA_NUM[work].get(key) or STHANA_NUM[work].get(key[:2])
            if sth:
                out.append((m.group(0), f"{work}.{sth}.{int(m.group(3))}.{int(m.group(4))}"))
            else:
                out.append((m.group(0), None))
        return out

    def context_limiting(self, concept_ids: list[str], exclude: set[str], k: int = 1) -> list[Hit]:
        if not concept_ids:
            return []
        cands = []
        for p in self.retriever.passages:
            if p.passage_id in exclude:
                continue
            ov = [c for c in concept_ids if c in p.concepts]
            if not ov:
                continue
            if NEG_RE.search(p.text_iast.lower()):
                cands.append((len(ov), p))
        cands.sort(key=lambda x: (-x[0], x[1].position))
        return [Hit(passage=p, matched_concepts=[c for c in concept_ids if c in p.concepts]) for _, p in cands[:k]]

    # ---------------------------------------------------------------- main
    def run(self, req: QueryRequest) -> RunResult:
        T0 = time.perf_counter()
        run_id = "run-" + uuid.uuid4().hex[:10]
        lang = req.lang
        stages: list[StageTrace] = []
        timings: dict[str, float] = {}
        llm_health_mode = self.llm.mode

        # 1. normalise
        t = time.perf_counter()
        raw = req.query
        iast = deva_to_iast(raw) if has_devanagari(raw) else None
        direct = self.terms.concepts_in_query(raw + " " + (req.case_text or ""))
        normalized = {"raw": raw, "nfc": nfc(raw), "script": "devanagari" if iast else "latin", "iast_transliteration": iast,
                      "concepts_direct": direct, "concepts_expanded": {}, "expansion_terms_raw": []}
        timings["normalize_ms"] = (time.perf_counter() - t) * 1000

        # 2. facts
        extracted = extract_facts(raw, self.terms, self.policy, req.case_text or "")
        facts = merge_facts(extracted, req.facts)
        meta_base = {"model_id": AYURPARAM_MODEL_ID, "model_revision": AYURPARAM_REVISION,
                     "prompt_version": PROMPT_VERSION, "corpus_version": self.store.corpus_version()}
        trace = RunTrace(run_id=run_id, created_at=now_iso(), cache_key=self.cache_key(req, facts), llm_mode=llm_health_mode,
                         model_id=AYURPARAM_MODEL_ID, model_revision=AYURPARAM_REVISION, inference_ran=False,
                         prompt_version=PROMPT_VERSION, corpus_version=self.store.corpus_version(),
                         rules_version=self.policy.version, terms_version=self.terms.version,
                         embed_model=EMBED_MODEL_ID if self.retriever.dense else "(dense unavailable)")

        def finish(status: str, evidence, claims, rejected, alerts, missing, notice, esc=None, unresolved=None) -> RunResult:
            timings["total_ms"] = (time.perf_counter() - T0) * 1000
            trace.stages = stages
            trace.timings_ms = {k: round(v, 1) for k, v in timings.items()}
            return RunResult(run_id=run_id, status=status, query=raw, lang=lang, normalized_query=normalized, facts=facts,
                             safety_alerts=alerts, missing_information=missing, evidence=evidence, claims=claims,
                             rejected_claims=rejected, answer_notice=notice, escalation_message=esc,
                             unresolved_questions=unresolved or [], trace=trace)

        # 3. safety precheck: escalation stops ordinary content
        esc = escalation(facts, self.policy, lang)
        if esc:
            rule_id, text = esc
            stages.append(StageTrace(name="safety_precheck", ran=True, mode="deterministic", detail={"escalated_by": rule_id}))
            b = _boundary(run_id, 1, text, meta_base, [f"policy rule {rule_id} / template T-URGENT-001 (review pending)"])
            return finish("escalated", [], [b], [], [], [], NOTICES[lang]["escalated"], esc=text)
        stages.append(StageTrace(name="safety_precheck", ran=True, mode="deterministic", detail={"escalated_by": None}))

        alerts = evaluate_rules(facts, self.policy, lang)
        missing = [a.question for a in alerts if a.action == "request_information" and a.question]
        herbs = next((f.values for f in facts if f.key == "proposed_herbs"), [])
        herb_withheld = bool(herbs) and any(a.action in ("withhold_positive_use", "request_information", "not_assessed") for a in alerts)

        # 4. explicit locator requests (fabricated-citation defence)
        boundary: list[Claim] = []
        requested_cards: list[EvidenceCard] = []
        for disp, pid in self.requested_locators(raw):
            p = self.store.get(pid) if pid else None
            if p is None:
                boundary.append(_boundary(run_id, len(boundary) + 1,
                    f"The requested reference '{disp}' does not resolve to any passage in the indexed editions (SARIT Caraka / Aṣṭāṅgahṛdaya). PRAMAAN will not cite or describe it.", meta_base))
            else:
                requested_cards.append(EvidenceCard(label="", passage=p, retrieval={"requested_locator": disp}, role="primary",
                                                    role_note="Explicitly requested locator (resolved)."))
        if boundary and not requested_cards:
            stages.append(StageTrace(name="locator_check", ran=True, mode="deterministic", detail={"unresolved": [b.text for b in boundary]}))
            sc = [_safety_claim(run_id, i + 1, a, meta_base) for i, a in enumerate(alerts)]
            return finish("insufficient_evidence", [], boundary + sc, [], alerts, missing, NOTICES[lang]["insufficient_evidence"])

        # 5. AyurParam stage 1: concept/query expansion
        expanded: dict[str, list[str]] = {}
        if req.use_model and self.llm.mode != "off":
            t = time.perf_counter()
            g = self.llm.generate(build_expand_prompt(raw), stage="expand", max_new_tokens=32)
            timings["expand_ms"] = (time.perf_counter() - t) * 1000
            if g.ok:
                trace.inference_ran = trace.inference_ran or g.mode == "live"
                terms_raw = parse_expansion(g.text)
                normalized["expansion_terms_raw"] = terms_raw
                for term in terms_raw:
                    for cid, al in self.terms.concepts_in_query(term).items():
                        if cid not in direct and cid in EXPANSION_ALLOWED:
                            expanded.setdefault(cid, []).append(term)
                normalized["concepts_expanded"] = expanded
            stages.append(StageTrace(name="ayurparam_expand", ran=g.ok, mode=g.mode, ms=round(g.ms, 1),
                                     detail={"raw_output": g.text[:400], "error": g.error, "prompt_tokens": g.prompt_tokens,
                                             "accepted_concepts": list(expanded), "note": "Only terms that map to the curated terminology are used, and only to widen retrieval; answerability uses the user's own terms."}))
        else:
            stages.append(StageTrace(name="ayurparam_expand", ran=False, mode="skipped" if not req.use_model else "unavailable"))

        # 6. retrieve
        t = time.perf_counter()
        concept_ids = list(direct) + [c for c in expanded if c not in direct]
        bm_text = raw + " " + (iast or "") + " " + " ".join(self.terms.expansion_terms(concept_ids))
        dense_q = raw + " " + " ".join(self.terms.by_id(c).label.get("en", "") for c in concept_ids if self.terms.by_id(c))
        hits, rinfo = self.retriever.search(bm_text, concept_ids, dense_q, limit=6, mode=req.retrieval_mode,
                                            source_filter=req.source_filter)
        timings["retrieve_ms"] = (time.perf_counter() - t) * 1000
        domain_direct = [c for c in direct if c not in self.terms.meta_ids]
        ok, why = answerability(hits, domain_direct)
        if requested_cards:
            ok, why = True, "explicit locator requested and resolved"
        stages.append(StageTrace(name="retrieve", ran=True, mode=rinfo["mode"], ms=round(timings["retrieve_ms"], 1),
                                 detail={**rinfo, "answerable": ok, "answerability_reason": why}))

        # 7. evidence cards (+ adjacent context, + context-limiting candidate)
        cards: list[EvidenceCard] = []
        seen = set()
        for c in requested_cards:
            cards.append(c)
            seen.add(c.passage.passage_id)
        for h in hits:
            if h.passage.passage_id in seen:
                continue
            seen.add(h.passage.passage_id)
            cards.append(EvidenceCard(label="", passage=h.passage, retrieval=h.as_dict(), role="primary", matched_concepts=h.matched_concepts))
        if cards:
            top = cards[0].passage
            if top.segment_type == "verse" and len(top.xml_ids) == 1:
                for nb in self.store.neighbours(top.passage_id, 1):
                    if nb.position == top.position + 1 and nb.passage_id not in seen:
                        cards.insert(1, EvidenceCard(label="", passage=nb, retrieval={"adjacent_to": top.passage_id}, role="adjacent_context",
                                                     role_note="Following segment, added because the top passage is a single half-verse."))
                        seen.add(nb.passage_id)
        # classical textual mentions of a proposed herb (never safety evidence)
        for herb in herbs:
            if self.terms.by_id(herb) is None:
                continue
            mentions = [p for p in self.retriever.passages if herb in p.concepts and p.passage_id not in seen]
            mentions.sort(key=lambda p: (0 if "herb-mentions" in p.modules else 1, -len(set(p.concepts) & set(direct)), p.source_id, p.position))
            for p in mentions[:2]:
                cards.append(EvidenceCard(label="", passage=p, retrieval={"search": f"herb mention: {herb}"}, role="primary",
                                          matched_concepts=[herb], role_note="Classical textual mention of the proposed herb (list/formulation context). Not modern safety evidence and not a recommendation."))
                seen.add(p.passage_id)
        if ok:
            for h in self.context_limiting(domain_direct, seen):
                cards.append(EvidenceCard(label="", passage=h.passage, retrieval={"search": "context-limiting (negation/restriction markers)"},
                                          role="context_limiting_candidate", matched_concepts=h.matched_concepts,
                                          role_note="Contains negation/restriction wording near a queried concept. Potential difference or limiting context; relationship NOT established - review needed."))
                seen.add(h.passage.passage_id)
        for i, c in enumerate(cards):
            c.label = f"E{i + 1}"

        safety_claims = [_safety_claim(run_id, i + 1, a, meta_base) for i, a in enumerate(alerts)]
        interaction_q = bool(INTERACTION_RE.search(raw))
        if interaction_q:
            boundary.append(_boundary(run_id, len(boundary) + 1,
                "Interaction question: PRAMAAN has no interaction database. Unless a cited safety statement above names this situation, the interaction is NOT ASSESSED (insufficient evidence) - this is not a 'safe' result.", meta_base))
        if herbs:
            boundary.append(_boundary(run_id, len(boundary) + 1,
                "Classical textual mentions of a herb are not modern safety evidence, and modern safety statements are not classical teaching; neither is an individual clearance.", meta_base))
        if not ok:
            stages.append(StageTrace(name="ayurparam_explain", ran=False, mode="skipped", detail={"reason": "not answerable: " + why}))
            return finish("insufficient_evidence", cards[:4], boundary + safety_claims, [], alerts, missing,
                          NOTICES[lang]["insufficient_evidence"] + f" ({why})",
                          unresolved=["Which source or chapter would a reviewer expect to address this?"])
        if herb_withheld:
            stages.append(StageTrace(name="ayurparam_explain", ran=False, mode="skipped", detail={"reason": "herb query with active safety rule / missing information"}))
            return finish("answered" if safety_claims else "insufficient_evidence", cards, boundary + safety_claims, [], alerts, missing,
                          NOTICES[lang]["herb_withheld"], unresolved=missing)
        if not req.use_model or self.llm.mode == "off":
            stages.append(StageTrace(name="ayurparam_explain", ran=False, mode="skipped"))
            return finish("retrieval_only", cards, boundary + safety_claims, [], alerts, missing, NOTICES[lang]["retrieval_only"])

        # 8. AyurParam stage 2: per-passage, evidence-bounded explanation (citation bound server-side)
        notes = [a.message for a in alerts if a.action in ("refuse_component",)]
        targets = [c for c in cards if c.role == "primary"][:3]
        attempts: list[dict] = []
        shown: list[Claim] = []
        rejected: list[Claim] = []
        run_meta = {"run_id": run_id, **meta_base}
        any_ok = False
        for card in targets:
            try:
                prompt, budget = build_passage_prompt(raw, lang, card, notes, max_new_tokens=90)
            except BudgetError as e:
                attempts.append({"evidence": card.label, "passage_id": card.passage.passage_id, "budget_error": str(e)})
                continue
            t = time.perf_counter()
            g = self.llm.generate(prompt, stage="explain", max_new_tokens=90, repetition_penalty=1.15)
            timings[f"explain_ms_{card.label}"] = (time.perf_counter() - t) * 1000
            att = {"evidence": card.label, "passage_id": card.passage.passage_id, "mode": g.mode, "ok": g.ok, "error": g.error,
                   "ms": round(g.ms, 1), "prompt_tokens": g.prompt_tokens, "completion_tokens": g.completion_tokens,
                   "budget": budget.as_dict(), "raw_output": g.text[:1200], "hardware": g.hardware}
            attempts.append(att)
            if not g.ok:
                if g.mode == "unavailable" and not any_ok:
                    break
                continue
            any_ok = True
            trace.inference_ran = trace.inference_ran or g.mode == "live"
            trace.hardware = g.hardware
            out = clean_output(g.text)
            truncated_tail = None
            if g.completion_tokens >= 90 and out and out[-1] not in ".!?।”\")":
                cut = max(out.rfind(". "), out.rfind("। "), out.rfind("? "), out.rfind("! "))
                truncated_tail = out[cut + 1:].strip() if cut >= 0 else out
                out = out[:cut + 1] if cut >= 0 else ""
            if "NOT RELEVANT" in out.upper() and len(out) < 40:
                att["model_said_not_relevant"] = True
                continue
            s_, r_ = build_claims(out, [card], self.terms, self.store, run_meta, withhold_positive=bool(alerts),
                                  bound_card=card, start_index=len(shown) + len(rejected))
            if truncated_tail:
                t_s, t_r = build_claims(truncated_tail, [card], self.terms, self.store, run_meta, withhold_positive=bool(alerts),
                                        bound_card=card, start_index=len(shown) + len(rejected) + len(s_) + len(r_))
                for c in t_s + t_r:
                    c.shown_in_answer = False
                    c.withheld_reason = "incomplete sentence (generation reached the output token limit)"
                r_ += t_s + t_r
            att["claims_shown"], att["claims_withheld"] = len(s_), len(r_)
            shown += s_
            rejected += r_
        mode = next((a.get("mode") for a in attempts if a.get("ok")), attempts[-1].get("mode", "error") if attempts else "error")
        stages.append(StageTrace(name="ayurparam_explain", ran=any_ok, mode=mode,
                                 ms=round(sum(v for k, v in timings.items() if k.startswith("explain")), 1),
                                 detail={"strategy": "one call per primary passage; citation bound to that passage by the backend",
                                         "attempts": attempts}))
        stages.append(StageTrace(name="validate", ran=True, mode="deterministic",
                                 detail={"shown": len(shown), "withheld": len(rejected),
                                         "withheld_reasons": [c.withheld_reason for c in rejected]}))
        if not any_ok:
            err = next((a.get("error") for a in attempts if a.get("error")), None)
            return finish("retrieval_only", cards, boundary + safety_claims, [], alerts, missing,
                          NOTICES[lang]["retrieval_only"] + (f" ({err})" if err else ""))
        if not shown:
            return finish("generation_failed", cards, boundary + safety_claims, rejected, alerts, missing, NOTICES[lang]["generation_failed"])
        return finish("answered", cards, shown + boundary + safety_claims, rejected, alerts, missing, NOTICES[lang]["answered"],
                      unresolved=missing)
